/* Child-owned mqtt_client tx/rx scratch buffers - AllocVec'd (never on the
 * child's stack, per CLAUDE.md's small-Amiga-shell-stack rule; the child's
 * own NP_StackSize is generous, but there is no reason to spend it here). */
#define MQTT_LIB_TXBUF_SIZE 2048
#define MQTT_LIB_RXBUF_SIZE 4096

/* Second AllocVec'd tx buffer, used ONLY for QoS 1 PUBLISH encode/retransmit
 * (see child_run()'s MQTTCMD_PUBLISH handling) - core's own mqtt_client
 * uses `txbuf` above for CONNECT/SUBSCRIBE/PINGREQ/DISCONNECT/its own QoS 0
 * publish path, and reusing it here would race the client's next process()
 * call rebuilding a different packet in the same bytes mid-retransmit-wait. */
#define MQTT_LIB_TXBUF2_SIZE 2048

/* QoS 1 PUBACK wait/retransmit budget: retransmit with DUP every ~5s, up to
 * 3 retransmits (4 sends total), then give up - see libraries/mqtt.h. */
#define MQTT_LIB_PUBACK_RETRY_MS   5000
#define MQTT_LIB_PUBACK_MAX_RETRIES 3

/* SUBACK wait budget - see libraries/mqtt.h. */
#define MQTT_LIB_SUBACK_TIMEOUT_MS 10000

/* Safety valve for a transport that persistently would-block inside a
 * single QoS 1 PUBLISH send, mirroring src/core/mqtt_client.c's own
 * MQTT_SEND_MAX_SPINS (not exported - core's send_all() is file-static). */
#define MQTT_LIB_SEND_MAX_SPINS 1000

/* Mirrors src/core/mqtt_client.c's send_all(): loop over transport->send()
 * until every byte is written. Needed here only because QoS 1 PUBLISH is
 * encoded and sent directly (core's mqtt_client_publish() only knows QoS 0 -
 * see mqtt_client.c) - everything else in this file goes through core's own
 * send_all() indirectly via mqtt_client_publish()/_subscribe()/_process(). */
static int lib_send_all(mqtt_transport *transport, const uint8_t *buf, int len)
{
    size_t sent = 0;
    int spins = 0;

    while (sent < (size_t)len) {
        int n = transport->send(transport->ctx, buf + sent, (size_t)len - sent);
        if (n < 0)
            return -1;
        if (n == 0) {
            if (++spins > MQTT_LIB_SEND_MAX_SPINS)
                return -1;
            continue;
        }
        sent += (size_t)n;
        spins = 0;
    }
    return 0;
}

/* --- small helper: deep-copy a caller string into an AllocVec'd buffer --- */
static STRPTR dupstr(const char *s)
{
    ULONG len;
    STRPTR copy;

    if (!s)
        return NULL;
    len = (ULONG)strlen(s) + 1;
    copy = (STRPTR)AllocVec(len, MEMF_PUBLIC);
    if (copy)
        memcpy(copy, s, (size_t)len);
    return copy;
}

/* --- mqtt_client_process() callback: one incoming PUBLISH -> one
 * AllocVec'd struct MqttMessage, delivered to the caller's ch_MsgPort. On
 * allocation failure the message is silently dropped, per the task's
 * delivery contract (there is nowhere else to put it).
 *
 * Also records PUBACK/SUBACK arrivals into h->ch_Ack* (see mqtt_priv.h) for
 * the QoS 1 publish-retransmit and SUBACK-wait loops in child_run() below -
 * those are plain child-local scratch fields, NOT queued as MqttMessages;
 * a caller never sees an ack packet via MQTT_GetMessage(). --- */
static void deliver_cb(void *user, const mqtt_packet *pkt)
{
    MqttClientHandle *h = (MqttClientHandle *)user;
    ULONG total;
    struct MqttMessage *m;
    STRPTR topic_copy;
    UBYTE *payload_copy;

    if (pkt->type == MQTT_PUBACK) {
        h->ch_AckType = MQTT_PUBACK;
        h->ch_AckId = pkt->u.ack.packet_id;
        h->ch_AckSeen = 1;
        return;
    }
    if (pkt->type == MQTT_SUBACK) {
        h->ch_AckType = MQTT_SUBACK;
        h->ch_AckId = pkt->u.suback.packet_id;
        h->ch_AckCode = (pkt->u.suback.count > 0) ? pkt->u.suback.codes[0]
                                                    : 0x80;
        h->ch_AckSeen = 1;
        return;
    }
    if (pkt->type != MQTT_PUBLISH)
        return;

    total = (ULONG)sizeof(struct MqttMessage) +
            (ULONG)pkt->u.publish.topic.len + 1u +
            pkt->u.publish.payload_len + 1u;

    m = (struct MqttMessage *)AllocVec(total, MEMF_PUBLIC | MEMF_CLEAR);
    if (!m)
        return;

    topic_copy = (STRPTR)(m + 1);
    memcpy(topic_copy, pkt->u.publish.topic.ptr, pkt->u.publish.topic.len);
    topic_copy[pkt->u.publish.topic.len] = '\0';

    payload_copy = (UBYTE *)topic_copy + pkt->u.publish.topic.len + 1;
    memcpy(payload_copy, pkt->u.publish.payload, pkt->u.publish.payload_len);
    payload_copy[pkt->u.publish.payload_len] = '\0';

    m->mm_Msg.mn_Node.ln_Type = NT_MESSAGE;
    m->mm_Msg.mn_Length = (UWORD)total;
    m->mm_Msg.mn_ReplyPort = NULL; /* never ReplyMsg()d - see mqtt.h */
    m->mm_Topic = topic_copy;
    m->mm_Payload = payload_copy;
    m->mm_PayloadLen = pkt->u.publish.payload_len;
    m->mm_Qos = pkt->u.publish.qos;
    m->mm_Retain = pkt->u.publish.retain;

    PutMsg(h->ch_MsgPort, &m->mm_Msg);
}

/* --- the child subprocess's whole life, from having a command port to
 * MQTTCMD_QUIT --- */
static void child_run(MqttClientHandle *h, struct MsgPort *cmd_port)
{
    uint8_t *txbuf, *rxbuf, *txbuf2;
    bsdsocket_ctx bctx;
    mqtt_transport transport;
    mqtt_client client;
    int have_client = 0;

    /* Child-owned outbound-PUBLISH packet-id counter, starting at 0x8000
     * and wrapping within 0x8000..0xFFFF - deliberately disjoint from
     * core's own next_packet_id (mqtt_client.c's alloc_packet_id(), used
     * for SUBSCRIBE, starts at 1 and wraps 0xFFFF -> 1). Because this
     * handle's commands are synchronous (do_command() is a blocking round
     * trip) and each client is one dedicated subprocess, at most one QoS 1
     * publish is ever outstanding at a time - there is no pending-publish
     * list here, just this one counter - so picking a disjoint id range is
     * about defensive clarity (a stray PUBACK for an old SUBSCRIBE-range id
     * can never be mistaken for a fresh publish ack) rather than strictly
     * required correctness. This is a local variable, not a file-scope
     * static: mqtt.library's single data segment (libinit.o) is shared by
     * every client subprocess, and CLAUDE.md forbids statics that would
     * break multiple simultaneous connections. */
    uint16_t next_pub_id = 0x8000;

    txbuf = (uint8_t *)AllocVec(MQTT_LIB_TXBUF_SIZE, MEMF_PUBLIC);
    rxbuf = (uint8_t *)AllocVec(MQTT_LIB_RXBUF_SIZE, MEMF_PUBLIC);
    txbuf2 = (uint8_t *)AllocVec(MQTT_LIB_TXBUF2_SIZE, MEMF_PUBLIC);

    for (;;) {
        struct Message *raw;

        if (!have_client)
            WaitPort(cmd_port);

        while ((raw = GetMsg(cmd_port)) != NULL) {
            MqttCmdMsg *cm = (MqttCmdMsg *)raw;

            switch (cm->cm_Cmd) {
            case MQTTCMD_CONNECT: {
                mqtt_connect_opts co;
                int rc;

                if (!txbuf || !rxbuf || !txbuf2) {
                    cm->cm_Result = MQTTERR_NOMEM;
                    break;
                }

                memset(&co, 0, sizeof(co));
                if (h->ch_Opts.mco_ClientID) {
                    co.client_id.ptr = (const char *)h->ch_Opts.mco_ClientID;
                    co.client_id.len =
                        (uint16_t)strlen((const char *)h->ch_Opts.mco_ClientID);
                }
                if (h->ch_Opts.mco_Username) {
                    co.username.ptr = (const char *)h->ch_Opts.mco_Username;
                    co.username.len =
                        (uint16_t)strlen((const char *)h->ch_Opts.mco_Username);
                    if (h->ch_Opts.mco_Password) {
                        co.password.ptr = (const char *)h->ch_Opts.mco_Password;
                        co.password.len =
                            (uint16_t)strlen((const char *)h->ch_Opts.mco_Password);
                    }
                }
                co.clean_session = h->ch_Opts.mco_CleanSession ? 1 : 0;
                co.keepalive = h->ch_Opts.mco_KeepAlive;

                if (transport_bsdsocket_connect(&transport, &bctx,
                        (const char *)h->ch_Host, h->ch_Port) != 0) {
                    cm->cm_Result = MQTTERR_NOTCONNECTED;
                    break;
                }
                /* Extra wakeup source for recv()'s WaitSelect poll, so a
                 * PUBLISH/SUBSCRIBE/DISCONNECT/QUIT arriving on cmd_port
                 * while we're pumping the connection is noticed within
                 * the poll instead of up to a second late. */
                bctx.break_sigmask = 1UL << cmd_port->mp_SigBit;

                mqtt_client_init(&client, &transport, &co, txbuf,
                                  MQTT_LIB_TXBUF_SIZE, rxbuf,
                                  MQTT_LIB_RXBUF_SIZE);
                rc = mqtt_client_connect(&client, tool_now_ms());
                while (rc == 0 &&
                       mqtt_client_get_state(&client) == MQTT_CS_CONNECTING) {
                    rc = mqtt_client_process(&client, tool_now_ms(),
                                              deliver_cb, h);
                }
                if (rc != 0 ||
                    mqtt_client_get_state(&client) != MQTT_CS_CONNECTED) {
                    cm->cm_Result =
                        (rc != 0) ? (LONG)rc
                                  : -(LONG)MQTT_CLIENT_ERR_CONNECT_REFUSED;
                    transport.close(transport.ctx);
                    break;
                }

                have_client = 1;
                cm->cm_Result = 0;
                break;
            }

            case MQTTCMD_PUBLISH:
                if (!have_client) {
                    cm->cm_Result = MQTTERR_NOTCONNECTED;
                    break;
                }
                if (cm->cm_Qos > 1) {
                    /* QoS 2 is out of scope - see docs/PROTOCOL.md. */
                    cm->cm_Result = -(LONG)MQTT_ERR_PROTOCOL;
                    break;
                }
                if (cm->cm_Qos == 0) {
                    cm->cm_Result = mqtt_client_publish(
                        &client, cm->cm_Topic, cm->cm_Payload,
                        cm->cm_PayloadLen, cm->cm_Retain != 0);
                    break;
                }

                /* QoS 1: core's mqtt_client_publish() only ever encodes
                 * QoS 0 (see mqtt_client.c), so this is encoded and sent
                 * directly here, then retransmitted (dup=1, same packet
                 * id) from the caller's own cm_Topic/cm_Payload - both
                 * stay valid for this whole synchronous exchange, so
                 * there's no need to copy them - every ~5s a PUBACK for
                 * this packet id doesn't arrive, up to
                 * MQTT_LIB_PUBACK_MAX_RETRIES times. */
                {
                    uint16_t pkt_id = next_pub_id;
                    int dup = 0;
                    int attempt;
                    LONG result = MQTTERR_TIMEOUT;

                    next_pub_id = (next_pub_id == 0xFFFF)
                                      ? (uint16_t)0x8000
                                      : (uint16_t)(next_pub_id + 1);

                    for (attempt = 0; attempt <= MQTT_LIB_PUBACK_MAX_RETRIES;
                         attempt++, dup = 1) {
                        int n;
                        uint32_t wait_start;
                        int done = 0;

                        n = mqtt_encode_publish(
                            txbuf2, MQTT_LIB_TXBUF2_SIZE, cm->cm_Topic,
                            cm->cm_Payload, cm->cm_PayloadLen, 1,
                            cm->cm_Retain != 0, dup, pkt_id);
                        if (n < 0) {
                            result = (LONG)n;
                            break;
                        }
                        if (lib_send_all(&transport, txbuf2, n) != 0) {
                            result = MQTTERR_NOTCONNECTED;
                            transport.close(transport.ctx);
                            have_client = 0;
                            break;
                        }

                        h->ch_AckSeen = 0;
                        /* Wrap-safe elapsed-time idiom (now - start >=
                         * timeout, unsigned), matching src/core's own
                         * keepalive arithmetic - an absolute deadline
                         * compare would misbehave across tool_now_ms()'s
                         * ~49.7-day uint32 wrap. */
                        wait_start = tool_now_ms();
                        for (;;) {
                            int rc = mqtt_client_process(&client,
                                                          tool_now_ms(),
                                                          deliver_cb, h);
                            if (rc != 0) {
                                result = (LONG)rc;
                                transport.close(transport.ctx);
                                have_client = 0;
                                done = 1;
                                break;
                            }
                            if (h->ch_AckSeen &&
                                h->ch_AckType == MQTT_PUBACK &&
                                h->ch_AckId == pkt_id) {
                                result = 0;
                                done = 1;
                                break;
                            }
                            if (tool_now_ms() - wait_start >=
                                MQTT_LIB_PUBACK_RETRY_MS)
                                break; /* retransmit, or give up if this
                                          was the last attempt */
                        }
                        if (done)
                            break;
                    }
                    cm->cm_Result = result;
                }
                break;

            case MQTTCMD_SUBSCRIBE:
                if (!have_client) {
                    cm->cm_Result = MQTTERR_NOTCONNECTED;
                    break;
                }
                {
                    LONG result = (LONG)mqtt_client_subscribe(
                        &client, cm->cm_Topic, cm->cm_Qos);

                    if (result == 0) {
                        uint32_t wait_start;

                        /* Core allocates the SUBSCRIBE's packet id
                         * internally (alloc_packet_id() is file-static in
                         * mqtt_client.c) and mqtt_client_subscribe() has no
                         * output parameter for it, so it can't be matched
                         * exactly without a further core change. Because
                         * do_command() is synchronous and this handle's
                         * child only ever has one SUBSCRIBE outstanding at
                         * a time, matching on "any SUBACK" is sound here -
                         * see the task notes for this deliberate deviation
                         * from packet-id matching. */
                        h->ch_AckSeen = 0;
                        /* Wrap-safe elapsed-time idiom - see the QoS 1
                         * PUBACK wait above. */
                        wait_start = tool_now_ms();
                        result = MQTTERR_TIMEOUT;
                        for (;;) {
                            int rc = mqtt_client_process(&client,
                                                          tool_now_ms(),
                                                          deliver_cb, h);
                            if (rc != 0) {
                                result = (LONG)rc;
                                transport.close(transport.ctx);
                                have_client = 0;
                                break;
                            }
                            if (h->ch_AckSeen &&
                                h->ch_AckType == MQTT_SUBACK) {
                                result = (h->ch_AckCode == 0x80)
                                             ? (LONG)MQTTERR_REFUSED
                                             : 0;
                                break;
                            }
                            if (tool_now_ms() - wait_start >=
                                MQTT_LIB_SUBACK_TIMEOUT_MS)
                                break;
                        }
                    }
                    cm->cm_Result = result;
                }
                break;

            case MQTTCMD_DISCONNECT:
                if (have_client) {
                    mqtt_client_disconnect(&client);
                    have_client = 0;
                }
                cm->cm_Result = 0;
                break;

            case MQTTCMD_QUIT: {
                struct Message *extra;

                if (have_client) {
                    mqtt_client_disconnect(&client);
                    have_client = 0;
                }
                if (txbuf)
                    FreeVec(txbuf);
                if (rxbuf)
                    FreeVec(rxbuf);
                if (txbuf2)
                    FreeVec(txbuf2);

                /* Defensive: reply anything else queued behind Quit so no
                 * caller is left waiting forever. In practice there
                 * should never be one - MQTT_DeleteClient() is documented
                 * as the only Quit sender, and callers hold the handle
                 * exclusively - but a stray command here must not hang. */
                while ((extra = GetMsg(cmd_port)) != NULL) {
                    ((MqttCmdMsg *)extra)->cm_Result = MQTTERR_NOTCONNECTED;
                    ReplyMsg(extra);
                }
                DeleteMsgPort(cmd_port);

                /* Canonical safe exit: Forbid() before the final ReplyMsg()
                 * so MQTT_DeleteClient() cannot resume and FreeVec() the
                 * handle out from under us until this task has actually
                 * finished dying (returning here ends the process - see
                 * CreateNewProcTags() below; no Exit()/RemTask() needed). */
                Forbid();
                ReplyMsg(&cm->cm_Msg);
                return;
            }

            default:
                cm->cm_Result = MQTTERR_NOTCONNECTED;
                break;
            }

            ReplyMsg(&cm->cm_Msg);
        }

        if (have_client) {
            int rc = mqtt_client_process(&client, tool_now_ms(), deliver_cb, h);
            if (rc != 0) {
                transport.close(transport.ctx);
                have_client = 0;
            }
        }
    }
}

/* --- NP_Entry target: no argc/argv, no libnix startup (see CLAUDE.md's
 * -noixemul note) - this is a plain function exec calls directly as the
 * new process's entire program. Returning from it terminates the process
 * (AmigaDOS RKRM: "processes die whenever their execution drops off at
 * the end of main(), or ... the final RTS"); no Exit()/RemTask() call is
 * needed or wanted. --- */
static void mqtt_child_entry(void)
{
    struct Process *me = (struct Process *)FindTask(NULL);
    struct Message *msg;
    MqttStartupMsg *startup;
    struct MsgPort *cmd_port;
    MqttClientHandle *handle;

    WaitPort(&me->pr_MsgPort);
    msg = GetMsg(&me->pr_MsgPort);
    startup = (MqttStartupMsg *)msg;

    /* Capture everything we need from the parent's stack frame before
     * ReplyMsg() - the instant that fires, the parent may resume and its
     * `startup` local can go out of scope (see guiport.c's rationale,
     * mirrored on this side of the exchange). */
    handle = startup->st_Handle;

    cmd_port = CreateMsgPort();
    startup->st_CmdPort = cmd_port; /* last touch of the parent's memory */
    ReplyMsg(msg);

    if (!cmd_port)
        return; /* OOM: parent sees a NULL cmd_port and fails the create */

    child_run(handle, cmd_port);
}

/* --- caller-side command round trip: PutMsg + Wait/GetMsg, mirroring
 * guiport.c. `cm_Msg` lives on THIS function's stack; the child only
 * touches it between receiving it and ReplyMsg()ing it, so the wait below
 * must never be abandoned early. --- */
static LONG do_command(MqttClientHandle *h, UWORD cmd, mqtt_str topic,
                        const UBYTE *payload, ULONG len, LONG retain,
                        UBYTE qos)
{
    MqttCmdMsg cm;
    struct MsgPort *reply;

    reply = CreateMsgPort();
    if (!reply)
        return MQTTERR_NOMEM;

    memset(&cm, 0, sizeof(cm));
    cm.cm_Msg.mn_Node.ln_Type = NT_MESSAGE;
    cm.cm_Msg.mn_Length = sizeof(cm);
    cm.cm_Msg.mn_ReplyPort = reply;
    cm.cm_Cmd = cmd;
    cm.cm_Topic = topic;
    cm.cm_Payload = payload;
    cm.cm_PayloadLen = len;
    cm.cm_Retain = retain;
    cm.cm_Qos = qos;

    PutMsg(h->ch_CmdPort, &cm.cm_Msg);

    for (;;) {
        Wait(1UL << reply->mp_SigBit);
        if (GetMsg(reply) != NULL)
            break;
    }

    DeleteMsgPort(reply);
    return cm.cm_Result;
}

/* ========================================================================
 * Public entry points (src/library/mqtt_lib.sfd order)
 * ==================================================================== */

APTR MQTT_CreateClient(struct Library *_base, STRPTR host, UWORD port,
                        struct MqttConnectOpts *opts)
{
    MqttClientHandle *h;
    struct MsgPort *startup_reply;
    struct Process *child;
    MqttStartupMsg startup;

    (void)_base;

    if (!host)
        return NULL;

    h = (MqttClientHandle *)AllocVec(sizeof(*h), MEMF_PUBLIC | MEMF_CLEAR);
    if (!h)
        return NULL;

    h->ch_Host = dupstr((const char *)host);
    if (!h->ch_Host)
        goto fail_handle;
    h->ch_Port = port;

    if (opts) {
        if (opts->mco_ClientID) {
            h->ch_ClientID = dupstr((const char *)opts->mco_ClientID);
            if (!h->ch_ClientID)
                goto fail_host;
        }
        if (opts->mco_Username) {
            h->ch_Username = dupstr((const char *)opts->mco_Username);
            if (!h->ch_Username)
                goto fail_host;
        }
        if (opts->mco_Password) {
            h->ch_Password = dupstr((const char *)opts->mco_Password);
            if (!h->ch_Password)
                goto fail_host;
        }
        h->ch_Opts.mco_KeepAlive = opts->mco_KeepAlive;
        h->ch_Opts.mco_CleanSession = opts->mco_CleanSession;
    }
    h->ch_Opts.mco_ClientID = h->ch_ClientID;
    h->ch_Opts.mco_Username = h->ch_Username;
    h->ch_Opts.mco_Password = h->ch_Password;

    h->ch_MsgPort = CreateMsgPort();
    if (!h->ch_MsgPort)
        goto fail_host;

    startup_reply = CreateMsgPort();
    if (!startup_reply)
        goto fail_msgport;

    /* Create the reply port BEFORE spawning the child, so a
     * CreateNewProcTags() failure never leaves an unreachable process
     * behind - nothing has been spawned yet at that point. */
    child = CreateNewProcTags(
        NP_Entry, (ULONG)(APTR)mqtt_child_entry,
        NP_StackSize, (ULONG)16384,
        NP_Name, (ULONG)(APTR) "mqtt.library client",
        NP_Priority, (ULONG)0,
        TAG_DONE);
    if (!child)
        goto fail_startup_reply;

    memset(&startup, 0, sizeof(startup));
    startup.st_Msg.mn_Node.ln_Type = NT_MESSAGE;
    startup.st_Msg.mn_Length = sizeof(startup);
    startup.st_Msg.mn_ReplyPort = startup_reply;
    startup.st_Handle = h;

    PutMsg(&child->pr_MsgPort, &startup.st_Msg);

    for (;;) {
        Wait(1UL << startup_reply->mp_SigBit);
        if (GetMsg(startup_reply) != NULL)
            break;
    }
    DeleteMsgPort(startup_reply);

    if (!startup.st_CmdPort)
        goto fail_msgport; /* child hit OOM and already exited */

    h->ch_CmdPort = startup.st_CmdPort;
    h->ch_Child = child;
    return (APTR)h;

fail_startup_reply:
    DeleteMsgPort(startup_reply);
fail_msgport:
    DeleteMsgPort(h->ch_MsgPort);
fail_host:
    if (h->ch_Password)
        FreeVec(h->ch_Password);
    if (h->ch_Username)
        FreeVec(h->ch_Username);
    if (h->ch_ClientID)
        FreeVec(h->ch_ClientID);
    FreeVec(h->ch_Host);
fail_handle:
    FreeVec(h);
    return NULL;
}

VOID MQTT_DeleteClient(struct Library *_base, APTR client)
{
    MqttClientHandle *h = (MqttClientHandle *)client;
    struct Message *msg;

    (void)_base;
    if (!h)
        return;

    if (h->ch_Connected) {
        (void)do_command(h, MQTTCMD_DISCONNECT, MQTT_STR_NULL, NULL, 0, 0, 0);
        h->ch_Connected = 0;
    }

    /* Waits for the child's ReplyMsg(), which (per child_run()'s
     * MQTTCMD_QUIT handling) only happens once the child has deleted its
     * own cmd_port and is about to return (ending the process) under
     * Forbid() - so by the time do_command() returns here, it's safe to
     * free everything below. */
    (void)do_command(h, MQTTCMD_QUIT, MQTT_STR_NULL, NULL, 0, 0, 0);

    while ((msg = GetMsg(h->ch_MsgPort)) != NULL)
        FreeVec(msg);
    DeleteMsgPort(h->ch_MsgPort);

    if (h->ch_Password)
        FreeVec(h->ch_Password);
    if (h->ch_Username)
        FreeVec(h->ch_Username);
    if (h->ch_ClientID)
        FreeVec(h->ch_ClientID);
    FreeVec(h->ch_Host);
    FreeVec(h);
}

LONG MQTT_Connect(struct Library *_base, APTR client)
{
    MqttClientHandle *h = (MqttClientHandle *)client;
    LONG rc;

    (void)_base;
    if (!h)
        return MQTTERR_NOTCONNECTED;

    rc = do_command(h, MQTTCMD_CONNECT, MQTT_STR_NULL, NULL, 0, 0, 0);
    if (rc == 0)
        h->ch_Connected = 1;
    return rc;
}

LONG MQTT_Publish(struct Library *_base, APTR client, STRPTR topic,
                   APTR payload, ULONG len, LONG retain, UBYTE qos)
{
    MqttClientHandle *h = (MqttClientHandle *)client;
    mqtt_str t;

    (void)_base;
    if (!h || !h->ch_Connected)
        return MQTTERR_NOTCONNECTED;
    if (!topic)
        return -(LONG)MQTT_ERR_PROTOCOL;
    if (qos > 1) /* QoS 2 is out of scope - see docs/PROTOCOL.md */
        return -(LONG)MQTT_ERR_PROTOCOL;

    t.ptr = (const char *)topic;
    t.len = (uint16_t)strlen((const char *)topic);

    return do_command(h, MQTTCMD_PUBLISH, t, (const UBYTE *)payload, len,
                       retain, qos);
}

LONG MQTT_Subscribe(struct Library *_base, APTR client, STRPTR filter,
                     UBYTE qos)
{
    MqttClientHandle *h = (MqttClientHandle *)client;
    mqtt_str f;

    (void)_base;
    if (!h || !h->ch_Connected)
        return MQTTERR_NOTCONNECTED;
    if (!filter)
        return -(LONG)MQTT_ERR_PROTOCOL;

    f.ptr = (const char *)filter;
    f.len = (uint16_t)strlen((const char *)filter);

    return do_command(h, MQTTCMD_SUBSCRIBE, f, NULL, 0, 0, qos);
}

struct MqttMessage *MQTT_GetMessage(struct Library *_base, APTR client)
{
    MqttClientHandle *h = (MqttClientHandle *)client;

    (void)_base;
    if (!h)
        return NULL;
    return (struct MqttMessage *)GetMsg(h->ch_MsgPort);
}

VOID MQTT_FreeMessage(struct Library *_base, APTR client,
                       struct MqttMessage *msg)
{
    (void)_base;
    (void)client;
    if (msg)
        FreeVec(msg);
}

VOID MQTT_Disconnect(struct Library *_base, APTR client)
{
    MqttClientHandle *h = (MqttClientHandle *)client;

    (void)_base;
    if (!h || !h->ch_Connected)
        return;

    (void)do_command(h, MQTTCMD_DISCONNECT, MQTT_STR_NULL, NULL, 0, 0, 0);
    h->ch_Connected = 0;
}
