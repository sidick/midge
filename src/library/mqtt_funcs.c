/* mqtt_funcs.c — mqtt.library's 8 public entry points (src/library/mqtt_lib.sfd)
 * plus the connection-subprocess implementation behind them.
 *
 * Architecture: each APTR client handle is one dedicated AmigaOS subprocess
 * (spawned by MQTT_CreateClient(), see mqtt_child_entry()/child_run() below)
 * owning the bsdsocket.library open, the socket, and an unmodified
 * src/core mqtt_client instance. The caller's task and the child
 * subprocess talk over two MsgPorts (see mqtt_priv.h's banner) using the
 * same PutMsg()/Wait()/GetMsg()/ReplyMsg() request-reply shape as
 * amiauth's src/amiga/guiport.c - the exchange is never abandoned early
 * because the far side holds pointers into the near side's stack frame for
 * its duration.
 *
 * Every function here takes `struct Library *_base` first (sfdc
 * --libarg=first): it is mqtt.library's own base, unused by any function
 * below (there is no per-library-instance state - MqttBase is only needed
 * by callers, to reach the LVO table). The gate stubs that place `_base`
 * into a6 and the real arguments into a0/d0/a1/... before calling the
 * plain C functions below are generated by sfdc --mode=gatestubs
 * (build/library-gen/gatestubs.c, see the Makefile's `library` target) -
 * see that file's --gateprefix=Gate_ output for the exact trampolines, and
 * libinit.c for how each gate stub is wired into the library's jump
 * table.
 */

