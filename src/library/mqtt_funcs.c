APTR MQTT_CreateClient(struct Library *_base, STRPTR host, UWORD port,
                        struct MqttConnectOpts *opts)
{
    MqttClientHandle *h;
    struct MsgPort *startup_reply;
    struct Process *child;
    MqttStartupMsg startup;

    (void)_base;

    if (!host)
        return NULL;

    h = (MqttClientHandle *)AllocVec(sizeof(*h), MEMF_PUBLIC | MEMF_CLEAR);
    if (!h)
        return NULL;

    h->ch_Host = dupstr((const char *)host);
    if (!h->ch_Host)
        goto fail_handle;
    h->ch_Port = port;

    if (opts) {
        if (opts->mco_ClientID) {
            h->ch_ClientID = dupstr((const char *)opts->mco_ClientID);
            if (!h->ch_ClientID)
                goto fail_host;
        }
        if (opts->mco_Username) {
            h->ch_Username = dupstr((const char *)opts->mco_Username);
            if (!h->ch_Username)
                goto fail_host;
        }
        if (opts->mco_Password) {
            h->ch_Password = dupstr((const char *)opts->mco_Password);
            if (!h->ch_Password)
                goto fail_host;
        }
        h->ch_Opts.mco_KeepAlive = opts->mco_KeepAlive;
        h->ch_Opts.mco_CleanSession = opts->mco_CleanSession;
    }
    h->ch_Opts.mco_ClientID = h->ch_ClientID;
    h->ch_Opts.mco_Username = h->ch_Username;
    h->ch_Opts.mco_Password = h->ch_Password;

    h->ch_MsgPort = CreateMsgPort();
    if (!h->ch_MsgPort)
        goto fail_host;

    startup_reply = CreateMsgPort();
    if (!startup_reply)
        goto fail_msgport;

    /* Create the reply port BEFORE spawning the child, so a
     * CreateNewProcTags() failure never leaves an unreachable process
     * behind - nothing has been spawned yet at that point. */
    child = CreateNewProcTags(
        NP_Entry, (ULONG)(APTR)mqtt_child_entry,
        NP_StackSize, (ULONG)16384,
        NP_Name, (ULONG)(APTR) "mqtt.library client",
        NP_Priority, (ULONG)0,
        TAG_DONE);
    if (!child)
        goto fail_startup_reply;

    memset(&startup, 0, sizeof(startup));
    startup.st_Msg.mn_Node.ln_Type = NT_MESSAGE;
    startup.st_Msg.mn_Length = sizeof(startup);
    startup.st_Msg.mn_ReplyPort = startup_reply;
    startup.st_Handle = h;

    PutMsg(&child->pr_MsgPort, &startup.st_Msg);

    for (;;) {
        Wait(1UL << startup_reply->mp_SigBit);
        if (GetMsg(startup_reply) != NULL)
            break;
    }
    DeleteMsgPort(startup_reply);

    if (!startup.st_CmdPort)
        goto fail_msgport; /* child hit OOM and already exited */

    h->ch_CmdPort = startup.st_CmdPort;
    h->ch_Child = child;
    return (APTR)h;

fail_startup_reply:
    DeleteMsgPort(startup_reply);
fail_msgport:
    DeleteMsgPort(h->ch_MsgPort);
fail_host:
    if (h->ch_Password)
        FreeVec(h->ch_Password);
    if (h->ch_Username)
        FreeVec(h->ch_Username);
    if (h->ch_ClientID)
        FreeVec(h->ch_ClientID);
    FreeVec(h->ch_Host);
fail_handle:
    FreeVec(h);
    return NULL;
}

VOID MQTT_DeleteClient(struct Library *_base, APTR client)
{
    MqttClientHandle *h = (MqttClientHandle *)client;
    struct Message *msg;

    (void)_base;
    if (!h)
        return;

    if (h->ch_Connected) {
        (void)do_command(h, MQTTCMD_DISCONNECT, MQTT_STR_NULL, NULL, 0, 0, 0);
        h->ch_Connected = 0;
    }

    /* Waits for the child's ReplyMsg(), which (per child_run()'s
     * MQTTCMD_QUIT handling) only happens once the child has deleted its
     * own cmd_port and is about to return (ending the process) under
     * Forbid() - so by the time do_command() returns here, it's safe to
     * free everything below. */
    (void)do_command(h, MQTTCMD_QUIT, MQTT_STR_NULL, NULL, 0, 0, 0);

    while ((msg = GetMsg(h->ch_MsgPort)) != NULL)
        FreeVec(msg);
    DeleteMsgPort(h->ch_MsgPort);

    if (h->ch_Password)
        FreeVec(h->ch_Password);
    if (h->ch_Username)
        FreeVec(h->ch_Username);
    if (h->ch_ClientID)
        FreeVec(h->ch_ClientID);
    FreeVec(h->ch_Host);
    FreeVec(h);
}

LONG MQTT_Connect(struct Library *_base, APTR client)
{
    MqttClientHandle *h = (MqttClientHandle *)client;
    LONG rc;

    (void)_base;
    if (!h)
        return MQTTERR_NOTCONNECTED;

    rc = do_command(h, MQTTCMD_CONNECT, MQTT_STR_NULL, NULL, 0, 0, 0);
    if (rc == 0)
        h->ch_Connected = 1;
    return rc;
}

LONG MQTT_Publish(struct Library *_base, APTR client, STRPTR topic,
                   APTR payload, ULONG len, LONG retain)
{
    MqttClientHandle *h = (MqttClientHandle *)client;
    mqtt_str t;

    (void)_base;
    if (!h || !h->ch_Connected)
        return MQTTERR_NOTCONNECTED;
    if (!topic)
        return -(LONG)MQTT_ERR_PROTOCOL;

    t.ptr = (const char *)topic;
    t.len = (uint16_t)strlen((const char *)topic);

    return do_command(h, MQTTCMD_PUBLISH, t, (const UBYTE *)payload, len,
                       retain, 0);
}

LONG MQTT_Subscribe(struct Library *_base, APTR client, STRPTR filter,
                     UBYTE qos)
{
    MqttClientHandle *h = (MqttClientHandle *)client;
    mqtt_str f;

    (void)_base;
    if (!h || !h->ch_Connected)
        return MQTTERR_NOTCONNECTED;
    if (!filter)
        return -(LONG)MQTT_ERR_PROTOCOL;

    f.ptr = (const char *)filter;
    f.len = (uint16_t)strlen((const char *)filter);

    return do_command(h, MQTTCMD_SUBSCRIBE, f, NULL, 0, 0, qos);
}

struct MqttMessage *MQTT_GetMessage(struct Library *_base, APTR client)
{
    MqttClientHandle *h = (MqttClientHandle *)client;

    (void)_base;
    if (!h)
        return NULL;
    return (struct MqttMessage *)GetMsg(h->ch_MsgPort);
}

VOID MQTT_FreeMessage(struct Library *_base, APTR client,
                       struct MqttMessage *msg)
{
    (void)_base;
    (void)client;
    if (msg)
        FreeVec(msg);
}

VOID MQTT_Disconnect(struct Library *_base, APTR client)
{
    MqttClientHandle *h = (MqttClientHandle *)client;

    (void)_base;
    if (!h || !h->ch_Connected)
        return;

    (void)do_command(h, MQTTCMD_DISCONNECT, MQTT_STR_NULL, NULL, 0, 0, 0);
    h->ch_Connected = 0;
}
